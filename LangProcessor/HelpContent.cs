    private static readonly (string, string)[] Method =
    {
        ("Рекурсивный спуск",
            "Каждому нетерминалу соответствует процедура: E, A, T, B, F. Процедура E вызывает T и A, " +
            "T вызывает F и B. A, встретив + или -, вызывает T и затем снова A; B, встретив *, / или %, " +
            "вызывает F и снова B. F принимает число, идентификатор или скобку: после «(» вызывается E " +
            "и проверяется «)».\n\n" +
            "Ошибки: недопустимый символ (лексическая), пропущенный операнд, пропущенный знак операции, " +
            "незакрытая и лишняя скобка (синтаксические). После ошибки разбор продолжается."),

        ("Тетрады",
            "Тетрады генерируются во время разбора: когда A или B распознаёт операцию, создаётся тетрада " +
            "(операция, левый операнд, правый операнд, ti) и ti становится левым операндом для следующей " +
            "операции. Поэтому * / % выполняются раньше + -, а операции одного приоритета — слева направо."),

        ("ПОЛИЗ",
            "ПОЛИЗ строится алгоритмом Дейкстры: числа сразу идут в выход, операции — в стек; перед " +
            "помещением операции из стека выталкиваются операции с приоритетом не ниже; «(» кладётся в стек, " +
            "«)» выталкивает операции до «(». Вычисление: числа кладутся в стек, операция снимает два числа " +
            "и кладёт результат."),
    };

